-- Staff shifts, schedules and evaluations (depends on 004_reservations).

CREATE TABLE IF NOT EXISTS work_shifts (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    start_time TIME        NOT NULL,
    end_time   TIME        NOT NULL,
    is_active  BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_shift_times CHECK (start_time < end_time)
);

CREATE TABLE IF NOT EXISTS staff_schedules (
    id             UUID    PRIMARY KEY DEFAULT uuidv7(),
    staff_id       UUID    NOT NULL REFERENCES user_profiles(id) ON DELETE CASCADE,
    reservation_id UUID    REFERENCES reservations(id)  ON DELETE SET NULL,
    shift_id       INTEGER REFERENCES work_shifts(id)   ON DELETE SET NULL,
    work_date      DATE    NOT NULL,
    start_time     TIME,
    end_time       TIME,
    status         TEXT    NOT NULL DEFAULT 'SCHEDULED'
                   CHECK (status IN ('SCHEDULED', 'CONFIRMED', 'IN_PROGRESS', 'COMPLETED', 'ABSENT')),
    assigned_by    UUID    REFERENCES user_profiles(id) ON DELETE SET NULL,
    notes          TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_schedules_staff_date ON staff_schedules(staff_id, work_date);

-- Copy start/end time from the shift and reject inverted time ranges.
CREATE OR REPLACE FUNCTION staff_schedules_set_times() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.shift_id IS NOT NULL THEN
        SELECT ws.start_time, ws.end_time
          INTO NEW.start_time, NEW.end_time
          FROM work_shifts ws
         WHERE ws.id = NEW.shift_id;
    END IF;

    IF NEW.start_time IS NOT NULL AND NEW.end_time IS NOT NULL AND NEW.start_time >= NEW.end_time THEN
        RAISE EXCEPTION 'start_time must be earlier than end_time'
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER trg_staff_schedules_set_times
    BEFORE INSERT OR UPDATE ON staff_schedules
    FOR EACH ROW EXECUTE FUNCTION staff_schedules_set_times();

CREATE TABLE IF NOT EXISTS staff_evaluations (
    id              UUID     PRIMARY KEY DEFAULT uuidv7(),
    staff_id        UUID     NOT NULL REFERENCES user_profiles(id) ON DELETE CASCADE,
    evaluator_id    UUID     NOT NULL REFERENCES user_profiles(id) ON DELETE RESTRICT,
    reservation_id  UUID     REFERENCES reservations(id)  ON DELETE SET NULL,
    -- A CHECK constraint replaces the two legacy validation triggers.
    rating          SMALLINT NOT NULL CONSTRAINT chk_evaluation_rating CHECK (rating BETWEEN 1 AND 5),
    feedback        TEXT,
    evaluation_date TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_evaluations_staff ON staff_evaluations(staff_id);
CREATE INDEX IF NOT EXISTS idx_evaluations_date  ON staff_evaluations(evaluation_date);
