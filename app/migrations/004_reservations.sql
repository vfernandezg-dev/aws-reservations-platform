-- Venues and reservations (depends on 003_quotations).

CREATE TABLE IF NOT EXISTS venues (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL,
    description TEXT,
    capacity    INTEGER       NOT NULL CHECK (capacity > 0),
    hourly_rate NUMERIC(10,2) CHECK (hourly_rate >= 0),
    amenities   JSONB,        -- available amenities
    is_active   BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reservations (
    id                  UUID          PRIMARY KEY DEFAULT uuidv7(),
    reservation_number  VARCHAR(50)   NOT NULL UNIQUE,
    client_id           UUID          NOT NULL REFERENCES user_profiles(id) ON DELETE RESTRICT,
    quotation_id        UUID          REFERENCES quotations(id)    ON DELETE SET NULL,  -- approved quotation
    venue_id            INTEGER       REFERENCES venues(id)        ON DELETE SET NULL,
    event_type          VARCHAR(100),
    event_date          DATE          NOT NULL,
    start_time          TIME          NOT NULL,
    end_time            TIME          NOT NULL,
    estimated_guests    INTEGER       NOT NULL CHECK (estimated_guests > 0),
    actual_guests       INTEGER       CHECK (actual_guests > 0),
    total_amount        NUMERIC(10,2) NOT NULL CHECK (total_amount >= 0),
    advance_payment     NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (advance_payment >= 0),
    remaining_balance   NUMERIC(10,2) NOT NULL CHECK (remaining_balance >= 0),
    status              TEXT          NOT NULL DEFAULT 'PENDING'
                        CHECK (status IN ('PENDING', 'CONFIRMED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    special_requests    TEXT,
    cancellation_reason TEXT,
    created_by          UUID          REFERENCES user_profiles(id) ON DELETE SET NULL,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT chk_reservation_times   CHECK (start_time < end_time),
    CONSTRAINT chk_reservation_balance CHECK (remaining_balance = total_amount - advance_payment)
);

CREATE OR REPLACE TRIGGER trg_reservations_updated_at
    BEFORE UPDATE ON reservations
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE INDEX IF NOT EXISTS idx_reservations_event_date ON reservations(event_date);
CREATE INDEX IF NOT EXISTS idx_reservations_client     ON reservations(client_id);

CREATE TABLE IF NOT EXISTS reservation_services (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id UUID          NOT NULL REFERENCES reservations(id) ON DELETE CASCADE,
    item_type      TEXT          NOT NULL CHECK (item_type IN ('SERVICE', 'PACKAGE')),
    item_id        INTEGER       NOT NULL,  -- services.id or packages.id
    quantity       INTEGER       NOT NULL DEFAULT 1,
    unit_price     NUMERIC(10,2) NOT NULL,
    total_price    NUMERIC(10,2) NOT NULL,
    status         TEXT          NOT NULL DEFAULT 'PENDING'
                   CHECK (status IN ('PENDING', 'CONFIRMED', 'IN_PROGRESS', 'COMPLETED')),
    assigned_staff JSONB,        -- IDs of assigned staff members
    notes          TEXT
);

CREATE INDEX IF NOT EXISTS idx_reservation_services_reservation ON reservation_services(reservation_id);
