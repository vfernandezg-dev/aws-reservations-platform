-- Notification templates, sent notifications and internal staff messages.

CREATE TABLE IF NOT EXISTS notification_templates (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL UNIQUE,
    type          TEXT         NOT NULL CHECK (type IN ('EMAIL', 'SMS', 'PUSH', 'IN_APP')),
    subject       VARCHAR(200),
    template_body TEXT         NOT NULL,
    variables     JSONB,       -- placeholders available to the template
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS notifications (
    id            UUID    PRIMARY KEY DEFAULT uuidv7(),
    recipient_id  UUID    NOT NULL REFERENCES user_profiles(id)          ON DELETE CASCADE,
    template_id   INTEGER REFERENCES notification_templates(id) ON DELETE SET NULL,
    type          TEXT    NOT NULL CHECK (type IN ('EMAIL', 'SMS', 'PUSH', 'IN_APP')),
    subject       VARCHAR(200),
    message       TEXT    NOT NULL,
    status        TEXT    NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SENT', 'DELIVERED', 'FAILED')),
    sent_at       TIMESTAMPTZ,
    delivered_at  TIMESTAMPTZ,
    error_message TEXT,
    metadata      JSONB,  -- delivery details (email, phone, ...)
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_notifications_recipient ON notifications(recipient_id);
CREATE INDEX IF NOT EXISTS idx_notifications_status    ON notifications(status);

CREATE TABLE IF NOT EXISTS internal_messages (
    id           UUID    PRIMARY KEY DEFAULT uuidv7(),
    sender_id    UUID    NOT NULL REFERENCES user_profiles(id) ON DELETE CASCADE,
    recipient_id UUID    NOT NULL REFERENCES user_profiles(id) ON DELETE CASCADE,
    subject      VARCHAR(200),
    message      TEXT    NOT NULL,
    priority     TEXT    NOT NULL DEFAULT 'NORMAL' CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    is_read      BOOLEAN NOT NULL DEFAULT FALSE,
    read_at      TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_internal_messages_recipient ON internal_messages(recipient_id, is_read);
CREATE INDEX IF NOT EXISTS idx_internal_messages_sender    ON internal_messages(sender_id);
