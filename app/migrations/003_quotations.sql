-- Quotations sent to clients before a reservation is confirmed.

CREATE TABLE IF NOT EXISTS quotations (
    id               UUID          PRIMARY KEY DEFAULT uuidv7(),
    client_id        UUID          NOT NULL REFERENCES user_profiles(id) ON DELETE RESTRICT,
    quotation_number VARCHAR(50)   NOT NULL UNIQUE,
    event_type       VARCHAR(100),
    event_date       DATE,
    estimated_guests INTEGER       CHECK (estimated_guests > 0),
    total_amount     NUMERIC(10,2) NOT NULL CHECK (total_amount >= 0),
    discount_amount  NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    tax_amount       NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (tax_amount >= 0),
    final_amount     NUMERIC(10,2) NOT NULL CHECK (final_amount >= 0),
    status           TEXT          NOT NULL DEFAULT 'DRAFT'
                     CHECK (status IN ('DRAFT', 'SENT', 'APPROVED', 'REJECTED', 'EXPIRED')),
    valid_until      DATE,
    notes            TEXT,
    created_by       UUID          REFERENCES user_profiles(id) ON DELETE SET NULL,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE OR REPLACE TRIGGER trg_quotations_updated_at
    BEFORE UPDATE ON quotations
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE INDEX IF NOT EXISTS idx_quotations_client ON quotations(client_id);

CREATE TABLE IF NOT EXISTS quotation_details (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id UUID          NOT NULL REFERENCES quotations(id) ON DELETE CASCADE,
    item_type    TEXT          NOT NULL CHECK (item_type IN ('SERVICE', 'PACKAGE')),
    item_id      INTEGER       NOT NULL,  -- services.id or packages.id
    quantity     INTEGER       NOT NULL DEFAULT 1 CHECK (quantity > 0),
    unit_price   NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    total_price  NUMERIC(10,2) NOT NULL CHECK (total_price >= 0),
    notes        TEXT
);

CREATE INDEX IF NOT EXISTS idx_quotation_details_quotation ON quotation_details(quotation_id);
