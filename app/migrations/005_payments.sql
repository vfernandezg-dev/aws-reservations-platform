-- Payment methods and payment transactions.

CREATE TABLE IF NOT EXISTS payment_methods (
    id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                      VARCHAR(50)  NOT NULL UNIQUE,
    description               TEXT,
    is_active                 BOOLEAN      NOT NULL DEFAULT TRUE,
    processing_fee_percentage NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (processing_fee_percentage >= 0)
);

CREATE TABLE IF NOT EXISTS payments (
    id                    UUID          PRIMARY KEY DEFAULT uuidv7(),
    reservation_id        UUID          NOT NULL REFERENCES reservations(id)    ON DELETE RESTRICT,
    payment_number        VARCHAR(50)   NOT NULL UNIQUE,
    payment_method_id     INTEGER       REFERENCES payment_methods(id) ON DELETE SET NULL,
    amount                NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    currency              CHAR(3)       NOT NULL DEFAULT 'USD',  -- ISO 4217 code
    payment_type          TEXT          NOT NULL CHECK (payment_type IN ('ADVANCE', 'PARTIAL', 'FULL', 'REFUND')),
    transaction_reference VARCHAR(100),  -- payment gateway reference
    status                TEXT          NOT NULL DEFAULT 'PENDING'
                          CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED', 'REFUNDED')),
    processed_by          UUID          REFERENCES user_profiles(id)   ON DELETE SET NULL,
    payment_date          TIMESTAMPTZ,
    notes                 TEXT,
    created_at            TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE OR REPLACE TRIGGER trg_payments_updated_at
    BEFORE UPDATE ON payments
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE INDEX IF NOT EXISTS idx_payments_reservation ON payments(reservation_id);

