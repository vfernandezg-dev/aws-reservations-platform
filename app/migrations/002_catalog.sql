-- Catalog: service categories, services and bundled packages.

CREATE TABLE IF NOT EXISTS service_categories (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description TEXT,
    is_active   BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS services (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id    INTEGER       NOT NULL REFERENCES service_categories(id) ON DELETE RESTRICT,
    name           VARCHAR(150)  NOT NULL,
    description    TEXT,
    base_price     NUMERIC(10,2) NOT NULL CHECK (base_price >= 0),
    duration_hours INTEGER,      -- estimated duration
    max_capacity   INTEGER,      -- maximum number of people
    requirements   TEXT,         -- special requirements
    is_active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE OR REPLACE TRIGGER trg_services_updated_at
    BEFORE UPDATE ON services
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE INDEX IF NOT EXISTS idx_services_category ON services(category_id);

CREATE TABLE IF NOT EXISTS packages (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(150)  NOT NULL,
    description         TEXT,
    total_price         NUMERIC(10,2) NOT NULL CHECK (total_price >= 0),
    discount_percentage NUMERIC(5,2)  NOT NULL DEFAULT 0 CHECK (discount_percentage BETWEEN 0 AND 100),
    duration_hours      INTEGER,
    max_capacity        INTEGER,
    is_active           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE OR REPLACE TRIGGER trg_packages_updated_at
    BEFORE UPDATE ON packages
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS package_services (
    package_id   INTEGER NOT NULL REFERENCES packages(id) ON DELETE CASCADE,
    service_id   INTEGER NOT NULL REFERENCES services(id) ON DELETE CASCADE,
    quantity     INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    custom_price NUMERIC(10,2),  -- price override inside this package
    PRIMARY KEY (package_id, service_id)
);
