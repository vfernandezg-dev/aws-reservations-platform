-- Users & roles. Authentication lives in Amazon Cognito; this table stores the
-- business profile linked to the Cognito user (JWT "sub" claim).

-- Shared trigger function: keeps updated_at current on every UPDATE
-- (PostgreSQL has no ON UPDATE CURRENT_TIMESTAMP column option).
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE TABLE IF NOT EXISTS user_profiles (
    id                UUID         PRIMARY KEY DEFAULT uuidv7(),
    cognito_user_id   TEXT         NOT NULL UNIQUE,
    user_type         TEXT         NOT NULL CHECK (user_type IN ('CLIENT', 'ADMIN', 'STAFF')),
    first_name        VARCHAR(100) NOT NULL,
    last_name         VARCHAR(100) NOT NULL,
    phone             VARCHAR(20),
    date_of_birth     DATE,
    address           TEXT,
    emergency_contact VARCHAR(100),
    emergency_phone   VARCHAR(20),
    is_active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE OR REPLACE TRIGGER trg_user_profiles_updated_at
    BEFORE UPDATE ON user_profiles
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE IF NOT EXISTS roles (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL UNIQUE,
    description TEXT,
    permissions JSONB,           -- permission list
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id     UUID    NOT NULL REFERENCES user_profiles(id) ON DELETE CASCADE,
    role_id     INTEGER NOT NULL REFERENCES roles(id)         ON DELETE CASCADE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    assigned_by UUID             REFERENCES user_profiles(id) ON DELETE SET NULL,
    PRIMARY KEY (user_id, role_id)
);

